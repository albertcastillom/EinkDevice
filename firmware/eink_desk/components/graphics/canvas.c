bool canvas_init(canvas_t *canvas, uint8_t *pixels, size_t buffer_size, uint16_t width, uint16_t height)
{
    if (canvas == NULL || pixels == NULL || width == 0 || height == 0) return false;
    const uint16_t stride = (uint16_t)((width + 7U) / 8U);
    if (buffer_size < (size_t)stride * height) return false;
    *canvas = (canvas_t){pixels, width, height, stride, buffer_size};
    return true;
}

void canvas_clear(canvas_t *canvas, bool black)
{
    if (canvas != NULL && canvas->pixels != NULL) memset(canvas->pixels, black ? 0x00 : 0xff, canvas->buffer_size);
}

void canvas_set_pixel(canvas_t *canvas, int x, int y, bool black)
{
    if (canvas == NULL || canvas->pixels == NULL || x < 0 || y < 0 || x >= canvas->width || y >= canvas->height) return;
    const size_t index = (size_t)y * canvas->stride + (size_t)x / 8U;
    const uint8_t mask = (uint8_t)(0x80U >> (x % 8));
    if (black) canvas->pixels[index] &= (uint8_t)~mask;
    else canvas->pixels[index] |= mask;
}

void canvas_fill_rect(canvas_t *canvas, int x, int y, int width, int height, bool black)
{
    if (width <= 0 || height <= 0) return;
    for (int py = y; py < y + height; ++py)
        for (int px = x; px < x + width; ++px) canvas_set_pixel(canvas, px, py, black);
}

void canvas_draw_rect(canvas_t *canvas, int x, int y, int width, int height, int thickness)
{
    if (width <= 0 || height <= 0 || thickness <= 0) return;
    canvas_fill_rect(canvas, x, y, width, thickness, true);
    canvas_fill_rect(canvas, x, y + height - thickness, width, thickness, true);
    canvas_fill_rect(canvas, x, y, thickness, height, true);
    canvas_fill_rect(canvas, x + width - thickness, y, thickness, height, true);
}

void canvas_draw_char(canvas_t *canvas, int x, int y, char character, int scale)
{
    if (scale <= 0) return;
    if (character >= 'a' && character <= 'z') character = (char)(character - 'a' + 'A');
    if (character < ' ' || character > 'Z') character = '?';
    const uint8_t *glyph = FONT_5X7[(unsigned char)character - ' '];
    for (int column = 0; column < 5; ++column)
        for (int row = 0; row < 7; ++row)
            if ((glyph[column] & (1U << row)) != 0)
                canvas_fill_rect(canvas, x + column * scale, y + row * scale, scale, scale, true);
}

void canvas_draw_text(canvas_t *canvas, int x, int y, const char *text, int scale)
{
    if (text == NULL) return;
    while (*text != '\0') {
        canvas_draw_char(canvas, x, y, *text, scale);
        x += 6 * scale;
        ++text;
    }
}
